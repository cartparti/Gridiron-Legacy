export function mascotKind(team) {
  const fixed = team.glyph ?? proTeamDef(team.id)?.glyph; // built-in pro teams pick their own
  if (fixed && GLYPHS[fixed]) return fixed;
  return KEYWORDS.find(([, re]) => re.test(team.name))?.[0] ?? 'shield';
}
